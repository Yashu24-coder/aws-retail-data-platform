"""Declarative data quality checks.

Rules live in checks.yml so a non-engineer can add one without touching Python.
Every check is a SQL query returning a single number, plus the expectation it
must satisfy. Error-severity failures fail the run; warn-severity failures are
reported and allowed through.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass
from pathlib import Path

import duckdb
import yaml

from ..config import Settings
from ..logging_setup import get_logger

log = get_logger("quality")

OPS = {
    "eq": lambda v, t: v == t,
    "gte": lambda v, t: v >= t,
    "lte": lambda v, t: v <= t,
    "gt": lambda v, t: v > t,
    "lt": lambda v, t: v < t,
}


@dataclass
class CheckResult:
    name: str
    table: str
    severity: str
    description: str
    observed: float
    operator: str
    threshold: float
    passed: bool


def load_rules(cfg: Settings) -> list[dict]:
    path = cfg.local_root.parent / "quality" / "checks.yml"
    if not path.exists():
        path = Path(__file__).resolve().parents[3] / "quality" / "checks.yml"
    return yaml.safe_load(path.read_text(encoding="utf-8"))["checks"]


def run_checks(con: duckdb.DuckDBPyConnection, cfg: Settings) -> list[CheckResult]:
    results: list[CheckResult] = []
    for rule in load_rules(cfg):
        observed = con.execute(rule["sql"]).fetchone()[0]
        observed = float(observed) if observed is not None else 0.0
        passed = OPS[rule["expect"]](observed, float(rule["threshold"]))
        results.append(CheckResult(
            name=rule["name"],
            table=rule.get("table", "-"),
            severity=rule.get("severity", "error"),
            description=rule.get("description", ""),
            observed=observed,
            operator=rule["expect"],
            threshold=float(rule["threshold"]),
            passed=passed,
        ))
        log.info("%s %-34s %10s %s %s", "PASS" if passed else "FAIL",
                 rule["name"], f"{observed:,.2f}", rule["expect"], rule["threshold"])
    return results


def summarise(results: list[CheckResult]) -> dict:
    errors = [r for r in results if not r.passed and r.severity == "error"]
    warnings = [r for r in results if not r.passed and r.severity == "warn"]
    return {
        "total": len(results),
        "passed": sum(1 for r in results if r.passed),
        "failed_errors": len(errors),
        "failed_warnings": len(warnings),
        "ok": not errors,
    }


def write_report(results: list[CheckResult], out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "data_quality.json").write_text(
        json.dumps([asdict(r) for r in results], indent=2), encoding="utf-8"
    )
    lines = [
        "# Data quality report",
        "",
        "Generated by `python -m retail_platform.cli quality`.",
        "",
        "| Check | Table | Observed | Rule | Severity | Result |",
        "|---|---|---|---|---|---|",
    ]
    for r in results:
        lines.append(
            f"| {r.name} | {r.table} | {r.observed:,.2f} | "
            f"{r.operator} {r.threshold:,.0f} | {r.severity} | "
            f"{'PASS' if r.passed else 'FAIL'} |"
        )
    (out_dir / "data_quality.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
